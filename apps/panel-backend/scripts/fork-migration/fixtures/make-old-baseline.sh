#!/usr/bin/env bash
# Regenerates old-fork-baseline.sql: the database a fresh install of the old fork
# (040410ac) has right after its 65 migrations, schema, seed rows and migration
# journal included. The tests of the move load it instead of needing the old
# repository: "an old-fork-schema DB" in one file.
#
#   ./make-old-baseline.sh <postgres-admin-url> [old-commit]
#   ./make-old-baseline.sh postgres://ice:ice@127.0.0.1:25433/postgres
#
# Needs git with the old commit fetched, node (the prisma CLI of this package),
# and pg_dump reachable as `docker exec <PG_CONTAINER> pg_dump` (default
# omega-check-pg) or on PATH. The database used is dropped and recreated.
set -euo pipefail
ADMIN_URL="${1:?postgres admin url}"
COMMIT="${2:-040410ac}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PKG="$(cd "$HERE/../../.." && pwd)"
REPO="$(git -C "$PKG" rev-parse --show-toplevel)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
DB="forkmig_baseline_$$"

git -C "$REPO" archive "$COMMIT" apps/panel-backend/prisma | tar -x -C "$WORK"
ln -s "$PKG/node_modules" "$WORK/apps/panel-backend/node_modules"
cat > "$WORK/apps/panel-backend/prisma.config.ts" <<'CFG'
import { defineConfig } from "prisma/config";
export default defineConfig({
  schema: "prisma/schema.prisma",
  migrations: { path: "prisma/migrations" },
  datasource: { url: process.env["DATABASE_URL"] },
});
CFG
BASE="${ADMIN_URL%/*}"
psql "$ADMIN_URL" -qc "DROP DATABASE IF EXISTS $DB" -c "CREATE DATABASE $DB" 2>/dev/null \
  || docker exec "${PG_CONTAINER:-omega-check-pg}" psql -U ice -d postgres -qc "DROP DATABASE IF EXISTS $DB" -c "CREATE DATABASE $DB"
(cd "$WORK/apps/panel-backend" && DATABASE_URL="$BASE/$DB" node node_modules/prisma/build/index.js migrate deploy)
if command -v pg_dump >/dev/null; then DUMP=(pg_dump "$BASE/$DB"); else DUMP=(docker exec "${PG_CONTAINER:-omega-check-pg}" pg_dump -U ice "$DB"); fi
{
  echo "-- The database of the old fork (${COMMIT}) after its 65 migrations. GENERATED by make-old-baseline.sh; do not edit."
  "${DUMP[@]}" --no-owner --no-privileges --no-comments --column-inserts \
    | grep -v "^SELECT pg_catalog.set_config('search_path'" | grep -v '^\\\(un\)\?restrict '
} > "$HERE/old-fork-baseline.sql"
psql "$ADMIN_URL" -qc "DROP DATABASE $DB" 2>/dev/null || docker exec "${PG_CONTAINER:-omega-check-pg}" psql -U ice -d postgres -qc "DROP DATABASE $DB"
echo "wrote $HERE/old-fork-baseline.sql"
